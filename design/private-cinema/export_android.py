"""Export the selected Private Cinema SVG as historical Android vector resources.

Superseded by design/icon-concepts/export_android_icons.py, which owns the current
phone resources. This script now writes into a local history folder so rerunning it
cannot overwrite the shipped icons.
"""
from pathlib import Path
import math
import shutil
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCE = REPO / 'design/icon-concepts'
RES = HERE / 'historical-android-res'
NS = '{http://www.w3.org/2000/svg}'
BACKGROUND = '#38233F'
GOLD = '#F0CE88'
SCALE = 0.84


def rectangle_path(element):
    x, y, w, h, r = [float(element.get(key, '0')) for key in ('x', 'y', 'width', 'height', 'rx')]
    return (f'M{x+r},{y} H{x+w-r} Q{x+w},{y} {x+w},{y+r} '
            f'V{y+h-r} Q{x+w},{y+h} {x+w-r},{y+h} H{x+r} '
            f'Q{x},{y+h} {x},{y+h-r} V{y+r} Q{x},{y} {x+r},{y} Z')


def geometry(element):
    tag = element.tag.removeprefix(NS)
    if tag == 'path':
        return element.attrib['d']
    if tag == 'rect':
        return rectangle_path(element)
    if tag == 'circle':
        x, y, r = [float(element.attrib[key]) for key in ('cx', 'cy', 'r')]
        return f'M{x-r},{y} A{r},{r} 0,1 0 {x+r},{y} A{r},{r} 0,1 0 {x-r},{y} Z'
    raise ValueError(tag)


def vector(paths, size, scale=None):
    group_open = '' if scale is None else f'    <group android:pivotX="256" android:pivotY="256" android:scaleX="{scale}" android:scaleY="{scale}">\n'
    group_close = '' if scale is None else '    </group>\n'
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="512"\n    android:viewportHeight="512">\n'
            + group_open + ''.join(paths) + group_close + '</vector>\n')


def write_resource(folder, name, content):
    destination = RES / folder / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    # Only these phone-specific resources are generated by this script.
    destination.write_text(content, encoding='utf-8')


root = ET.parse(SOURCE / '05-cinema-ticket.svg').getroot()
elements = [node for node in root if node.tag in {NS+'rect', NS+'circle', NS+'path'}]
paths = [f'    <path android:fillColor="{node.attrib["fill"]}" android:pathData="{geometry(node)}" />\n' for node in elements]
write_resource('drawable', 'jellycine_logo.xml', vector(paths, 128))
write_resource('drawable', 'ic_private_cinema_foreground.xml', vector(paths[1:], 108, SCALE))
write_resource('drawable', 'ic_private_cinema_background.xml', vector([
    f'    <path android:fillColor="{BACKGROUND}" android:pathData="M0,0 H512 V512 H0 Z" />\n'
], 108))
# One even-odd compound path preserves transparent lens, play and perforations
# under system tinting. The play is a positive island inside the lens cutout.
compound = ' '.join(geometry(node) for node in elements[1:])
write_resource('drawable', 'ic_private_cinema_monochrome.xml', vector([
    f'    <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="{compound}" />\n'
], 108, SCALE))
adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_private_cinema_background" />
    <foreground android:drawable="@drawable/ic_private_cinema_foreground" />
    <monochrome android:drawable="@drawable/ic_private_cinema_monochrome" />
</adaptive-icon>
'''
for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
    write_resource('mipmap-anydpi', name, adaptive)
for name in ('ic_splash_logo.xml', 'splash_icon.xml'):
    write_resource('drawable', name, '''<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/ic_private_cinema_foreground" />
</layer-list>
''')

# Every foreground point is inside a conservative bounding circle, so all
# Android adaptive mask shapes retain the ticket within the 66dp safe zone.
radius = math.hypot(146, 105) * SCALE * 108 / 512
assert radius < 33, radius

for filename in ('05-cinema-ticket.svg', '05-cinema-ticket-1024.png'):
    shutil.copyfile(SOURCE / filename, HERE / filename)

original = Image.open(SOURCE / '05-cinema-ticket-1024.png').convert('RGBA')
foreground = original.copy()
monochrome = original.copy()
foreground.putdata([(0,0,0,0) if p[3] == 0 or p[:3] == (56,35,63) else p for p in original.get_flattened_data()])
monochrome.putdata([(255,255,255,255) if p[3] and p[:3] == (240,206,136) else (0,0,0,0) for p in original.get_flattened_data()])


def launcher_preview(round_mask=False, themed=None):
    canvas = Image.new('RGBA', (1024,1024), themed[0] if themed else BACKGROUND)
    mark = monochrome.copy() if themed else foreground.copy()
    if themed:
        colored = Image.new('RGBA', mark.size, themed[1])
        colored.putalpha(mark.getchannel('A'))
        mark = colored
    mark = mark.resize((860,860), Image.Resampling.LANCZOS)
    canvas.alpha_composite(mark, (82,82))
    # Typical launcher visible region: central 72dp of the 108dp layers.
    canvas = canvas.crop((171,171,853,853)).resize((240,240), Image.Resampling.LANCZOS)
    mask = Image.new('L', (960,960))
    draw = ImageDraw.Draw(mask)
    if round_mask:
        draw.ellipse((0,0,959,959), fill=255)
    else:
        draw.rounded_rectangle((0,0,959,959), radius=210, fill=255)
    canvas.putalpha(mask.resize((240,240), Image.Resampling.LANCZOS))
    return canvas

